export const CARD_MAP: Record<string, CombatCard> = Object.fromEntries(
  CARD_DATABASE.map((c) => [c.id, c])
);

export function getCardById(
  id: string,
  customCards?: CombatCard[]
): CombatCard | undefined {
  if (CARD_MAP[id]) return CARD_MAP[id];
  return customCards?.find((c) => c.id === id);
}

